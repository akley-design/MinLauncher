import type { BlockStyle } from "./voxel";

function cube(
  tile: BlockStyle["top"],
  tint: string,
  extra: Partial<BlockStyle> = {},
): BlockStyle {
  return { top: tile, side: tile, bottom: tile, tint, ...extra };
}

